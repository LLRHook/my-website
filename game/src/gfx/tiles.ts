export type Light = "day" | "dusk" | "night";
export function lightAt(hour: number): Light {
  return hour >= 7 && hour < 17 ? "day" : hour >= 17 && hour < 20 ? "dusk" : "night";
}
// Palette-to-palette remaps, never alpha tinting or blended pixels.
export function remap(index: number, light: Light): number {
  if (light === "day") {
    return index;
  }
  const dusk: Readonly<Record<number, number>> = { 5: 18, 6: 18, 7: 19, 8: 20, 11: 16, 12: 17, 3: 19 };
  const night: Readonly<Record<number, number>> = {
    5: 12, 6: 27, 7: 10, 8: 9, 9: 10, 11: 14, 12: 13, 18: 28, 19: 29, 20: 15, 21: 0, 24: 2, 27: 28,
  };
  return (light === "dusk" ? dusk : night)[index] ?? index;
}
