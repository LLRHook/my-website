function switchTile(initial: readonly string[], pressed: boolean): TileDef {
  const glyph = initial.flatMap((row) => {
    const pixels = `0011${[...row].map((cell) => cell === "2" ? "22" : "11").join("")}1100`;
    return [pixels, pixels];
  });
  const rows = ["0000000000000000", "0011111111111100", "0012222222222100",
    ...glyph, "0011111111111100", "0001111111111000", "0000000000000000"];
  return { walkable: true, colours: pressed ? [27, 9, 6] : [27, 28, 5], rows };
}

